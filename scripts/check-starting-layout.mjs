import assert from "node:assert/strict";
import {
  STARTING_LAYOUT_SAVE_ENDPOINT,
  STARTING_LAYOUT_STORAGE_KEY,
  applyStartingLayout,
  captureStartingLayout,
  createStartingLayoutModuleSource,
  findBuildTreeColliderSelection,
  loadStartingLayout,
  normalizeStartingLayout,
  saveStartingLayout,
  saveStartingLayoutToProject,
} from "../src/startingLayout.js";

const tree = {
  id: "editor-world-4",
  kind: "tree",
  item: { id: "tree", placement: "tree", textureKey: "trees", frame: 0 },
  point: { x: 32, y: 48 },
  sprites: [{ runtimeOnly: true }],
  bounds: { left: 32, right: 80, top: 48, bottom: 112 },
  collider: true,
  colliderBounds: { left: 48, right: 64, top: 96, bottom: 112 },
  colliderGroup: "build:tree",
};
const colliderEntry = {
  id: tree.id,
  groupKey: "build:tree",
  rect: { ...tree.colliderBounds },
  base: { ...tree.colliderBounds },
};
const storageValues = new Map();
const storage = {
  getItem: (key) => storageValues.get(key) ?? null,
  setItem: (key, value) => storageValues.set(key, value),
  removeItem: (key) => storageValues.delete(key),
};
const captureScene = {
  nextBuildObjectId: 4,
  buildCellKey: ({ x, y }) => `${x},${y}`,
  buildPlacedObjects: new Map([[tree.id, tree]]),
  floorSprites: new Map(),
  wallSprites: new Map([["render-wall-a", {}]]),
  worldLayout: {
    houseFloorTiles: [{ x: 2, y: 3 }],
    houseWallTiles: [{ id: "render-wall-a" }, { id: "render-wall-b" }],
    getWorldObjectColliders: () => [colliderEntry],
  },
  facilityRuntime: { getDefinitions: () => [{ id: "home-table-01", facilityType: "table" }] },
  debrisRuntime: { getBedDefinitions: () => [{ id: "home-bed-01", position: { x: 8, y: 8 } }] },
};

const captured = captureStartingLayout(captureScene);
assert.deepEqual(captured.removedCanonicalFloors, ["32,48"], "missing canonical floor cells are serialized");
assert.deepEqual(captured.removedCanonicalWalls, ["render-wall-b"], "missing canonical wall descriptors are serialized");
assert.equal(captured.buildObjects[0].sprites, undefined, "Phaser visuals never enter the starting layout");
assert.equal(captured.buildObjects[0].colliderGroup, "build:tree");

saveStartingLayout(captureScene, storage);
assert(storageValues.has(STARTING_LAYOUT_STORAGE_KEY), "the authored layout uses a dedicated preference key");
assert.deepEqual(loadStartingLayout(storage), captured, "stored layouts normalize through a deterministic round trip");
storage.removeItem(STARTING_LAYOUT_STORAGE_KEY);
assert.deepEqual(loadStartingLayout(storage, captured), captured, "the checked-in project default is used without a local authoring override");

const moduleSource = createStartingLayoutModuleSource(captured);
assert(moduleSource.startsWith("// Generated by the in-game debug authoring action."));
assert(moduleSource.includes('"editor-world-4"') && moduleSource.endsWith(";\n"));

const requests = [];
await saveStartingLayoutToProject(captureScene, {
  storage,
  baseUrl: "/NestledBurrow/",
  fetchImpl: async (url, options) => {
    requests.push({ url, options });
    return { ok: true, text: async () => "" };
  },
});
assert.equal(requests[0].url, `/NestledBurrow/${STARTING_LAYOUT_SAVE_ENDPOINT}`);
assert.equal(requests[0].options.method, "POST");
assert.deepEqual(normalizeStartingLayout(JSON.parse(requests[0].options.body)), captured);

const previous = storage.getItem(STARTING_LAYOUT_STORAGE_KEY);
await assert.rejects(() => saveStartingLayoutToProject(captureScene, {
  storage,
  baseUrl: "/NestledBurrow/",
  fetchImpl: async () => ({ ok: false, status: 503, text: async () => "unavailable" }),
}), /unavailable/);
assert.equal(storage.getItem(STARTING_LAYOUT_STORAGE_KEY), previous, "failed project writes preserve the previous valid local default");

const shuffled = normalizeStartingLayout({
  ...captured,
  removedCanonicalWalls: ["z", "a", "z"],
  facilities: [{ id: "z" }, { id: "a" }],
});
assert.deepEqual(shuffled.removedCanonicalWalls, ["a", "z"]);
assert.deepEqual(shuffled.facilities.map(({ id }) => id), ["a", "z"]);
assert.throws(() => normalizeStartingLayout({ ...captured, buildObjects: [captured.buildObjects[0], captured.buildObjects[0]] }), /duplicate ID/);

assert.equal(
  findBuildTreeColliderSelection(captureScene, { x: 40, y: 56 })?.id,
  tree.id,
  "the tree crown selects the trunk collider even outside its physical rectangle",
);
assert.equal(findBuildTreeColliderSelection(captureScene, { x: 10, y: 10 }), null);

let floorDestroyed = false;
const restoredObjects = [];
const removedWalls = [];
const applyScene = {
  nextBuildObjectId: 0,
  buildPlacedObjects: new Map(),
  floorSprites: new Map([["32,48", { sprite: { destroy: () => { floorDestroyed = true; } } }]]),
  wallSprites: new Map([["render-wall-b", { tile: { worldX: 64, worldY: 80 } }]]),
  worldLayout: {},
  removeBuildPlacedObjectById: () => null,
  demolishBuildObject(point, type) { removedWalls.push({ point, type }); this.wallSprites.delete("render-wall-b"); },
  restoreBuildPlacedObject(object) { restoredObjects.push(object); this.buildPlacedObjects.set(object.id, object); return true; },
  facilityRuntime: {
    getDefinitions: () => [], remove: () => true, getDefinition: () => null, move: () => ({}),
    add: () => ({}), restore: () => true, replace: () => true, syncKitchenVisuals: () => {},
  },
  debrisRuntime: {
    getBedDefinitions: () => [], removeBed: () => true, addBed: () => ({}), restoreBed: () => true,
  },
  interactionRuntime: { refresh: () => {} },
  clearBuildPreview: () => {},
};
applyStartingLayout(applyScene, captured);
assert.equal(floorDestroyed, true);
assert.equal(removedWalls.length, 1);
assert.equal(restoredObjects[0].id, tree.id);
assert.equal(applyScene.nextBuildObjectId, 4);

console.log("starting layout contract passed: project defaults round-trip and build trees select by visible bounds");
