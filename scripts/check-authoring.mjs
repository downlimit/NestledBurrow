import assert from "node:assert/strict";
import {
  AUTHORING_BACKUP_VERSION,
  createAuthoringBackup,
  createAuthoringBackupSource,
  restoreAuthoringBackup,
} from "../src/authoringBackup.js";
import {
  COLLIDER_DEBUG_STORAGE_KEY,
  COLLIDER_DEFAULTS_SAVE_ENDPOINT,
  createColliderDefaultsModuleSource,
  mergeColliderOverrides,
  normalizeColliderOverrides,
  saveColliderDebugOverrides,
  saveColliderDebugOverridesToProject,
} from "../src/colliderDebugOverrides.js";
import {
  PLANTED_TREE_PROFILE_ID,
  applyPlantedTreeWork,
  createPlantedTreeDefinition,
  resolveColliderSelectionPointer,
} from "../src/editorAuthoringRuntime.js";
import { createFreshInventory, getInventoryQuantity } from "../src/inventoryDomain.js";
import {
  STARTING_LAYOUT_STORAGE_KEY,
  STARTING_LAYOUT_VERSION,
  captureStartingLayout,
  createStartingLayoutModuleSource,
  loadStartingLayout,
  normalizeStartingLayout,
  saveStartingLayoutToProject,
} from "../src/startingLayout.js";
import STARTING_LAYOUT_DEFAULT from "../src/startingLayoutDefault.js";
import { getResourceProfile } from "../src/resourceDomain.js";

function createStorage() {
  return {
    values: new Map(),
    getItem(key) { return this.values.get(key) ?? null; },
    setItem(key, value) { this.values.set(key, value); },
    removeItem(key) { this.values.delete(key); },
  };
}

const normalized = normalizeColliderOverrides({
  "resource:tree-planted": { left: -2.2, right: 3.7, top: 1, bottom: 0 },
  invalid: { left: 0, right: 0, top: Number.NaN, bottom: 0 },
  "facility:table": { left: 1, right: 2, top: 3, bottom: 4 },
});
assert.deepEqual(Object.keys(normalized), ["facility:table", "resource:tree-planted"]);
assert.deepEqual(normalized["resource:tree-planted"], { left: -2, right: 4, top: 1, bottom: 0 });
assert.deepEqual(
  mergeColliderOverrides(
    { "facility:table": { left: 1, right: 1, top: 1, bottom: 1 } },
    { "facility:table": { left: 2, right: 2, top: 2, bottom: 2 } },
  )["facility:table"],
  { left: 2, right: 2, top: 2, bottom: 2 },
  "local draft overrides canonical defaults until it is applied",
);
const colliderModule = createColliderDefaultsModuleSource(normalized);
assert(colliderModule.startsWith("// Generated by the in-game collider editor."));
assert(colliderModule.includes('"resource:tree-planted"'));

const storage = createStorage();
const requests = [];
await saveColliderDebugOverridesToProject(normalized, {
  storage,
  baseUrl: "/NestledBurrow/",
  fetchImpl: async (url, options) => {
    requests.push({ url, options });
    return { ok: true, text: async () => "" };
  },
});
assert.equal(requests[0].url, `/NestledBurrow/${COLLIDER_DEFAULTS_SAVE_ENDPOINT}`);
assert.equal(requests[0].options.method, "POST");
assert.deepEqual(JSON.parse(requests[0].options.body), normalized);
assert.equal(storage.getItem(COLLIDER_DEBUG_STORAGE_KEY), null, "successful project write clears the local draft cache");

const failedStorage = createStorage();
await assert.rejects(() => saveColliderDebugOverridesToProject(normalized, {
  storage: failedStorage,
  fetchImpl: async () => ({ ok: false, status: 503, text: async () => "unavailable" }),
}), (error) => error.localSaved === true && /unavailable/.test(error.message));
assert(failedStorage.getItem(COLLIDER_DEBUG_STORAGE_KEY), "failed project write keeps the local collider edit");

const plantObject = {
  id: "editor-world-9",
  kind: "plant",
  item: {
    id: "tree",
    placement: "tree",
    objectType: "plant",
    resourceProfileId: PLANTED_TREE_PROFILE_ID,
    textureKey: "trees",
    frame: 0,
  },
  point: { x: 32, y: 48 },
  bounds: { left: 32, right: 80, top: 48, bottom: 112 },
  collider: true,
  colliderBounds: { left: 48, right: 64, top: 96, bottom: 112 },
  colliderGroup: `resource:${PLANTED_TREE_PROFILE_ID}`,
  sprites: [{ runtimeOnly: true }],
};
const definition = createPlantedTreeDefinition(plantObject);
assert.equal(definition.profileId, PLANTED_TREE_PROFILE_ID);
assert.deepEqual(definition.position, { x: 56, y: 104 });

const sessionState = {
  gameplay: {
    currentEnergy: 100,
    inventory: createFreshInventory(),
    resourceNodes: {},
  },
};
let result = null;
for (let hit = 0; hit < 7; hit += 1) {
  result = applyPlantedTreeWork(sessionState, definition, {
    damage: 1,
    energyPerHit: 0.5,
    tuning: { smallLogChopHp: 7 },
  });
}
assert.equal(result.status, "cleared");
assert.deepEqual(result.reward, { resource: "wood", amount: 5 });
assert.equal(getInventoryQuantity(sessionState.gameplay.inventory, "wood"), 5, "a planted tree yields exactly five inventory wood");
assert.equal(result.inventory?.mutated, true);
assert.equal(sessionState.gameplay.currentEnergy, 96.5);
assert.equal(getResourceProfile(PLANTED_TREE_PROFILE_ID).kind, "plant");

const colliderEntry = {
  id: plantObject.id,
  groupKey: `resource:${PLANTED_TREE_PROFILE_ID}`,
  rect: plantObject.colliderBounds,
  base: plantObject.colliderBounds,
};
const selectionBounds = new Map([[plantObject.id, plantObject.bounds]]);
const crownClick = resolveColliderSelectionPointer([colliderEntry], selectionBounds, { worldX: 40, worldY: 56 });
assert.deepEqual(
  { x: crownClick.worldX, y: crownClick.worldY },
  { x: 56, y: 104 },
  "the visible crown selects the one physical collider without creating a second debug rectangle",
);
const trunkClick = { worldX: 55, worldY: 103 };
assert.equal(resolveColliderSelectionPointer([colliderEntry], selectionBounds, trunkClick), trunkClick, "direct collider hits keep normal editor behavior");

function captureScene(cleared) {
  return {
    nextBuildObjectId: 9,
    buildPlacedObjects: new Map([[plantObject.id, plantObject]]),
    buildCellKey: ({ x, y }) => `${x},${y}`,
    floorSprites: new Map(),
    wallSprites: new Map(),
    worldLayout: {
      houseFloorTiles: [],
      houseWallTiles: [],
    },
    facilityRuntime: { getDefinitions: () => [] },
    meleeRuntime: {
      getStartingLayoutFurniture: () => [{ id: "training-dummy-01", kind: "training-dummy", position: { x: 144, y: 50 } }],
    },
    debrisRuntime: { getBedDefinitions: () => [] },
    sessionState: {
      gameplay: {
        resourceNodes: {
          [plantObject.id]: { cleared, progress: cleared ? 1 : 0 },
        },
      },
    },
  };
}
const activeLayout = captureStartingLayout(captureScene(false));
assert.equal(activeLayout.version, STARTING_LAYOUT_VERSION);
assert.equal(activeLayout.buildObjects.length, 1);
assert.deepEqual(activeLayout.furniture, [{ id: "training-dummy-01", kind: "training-dummy", position: { x: 144, y: 50 } }]);
assert.equal(activeLayout.buildObjects[0].kind, "plant");
assert.equal(activeLayout.buildObjects[0].sprites, undefined);
assert.equal(captureStartingLayout(captureScene(true)).buildObjects.length, 0, "a chopped plant is not authored into the next starting layout");
const layoutModule = createStartingLayoutModuleSource(activeLayout);
assert(layoutModule.includes('"kind": "plant"'));
const canonicalLayout = normalizeStartingLayout(STARTING_LAYOUT_DEFAULT);
assert.equal(canonicalLayout.buildObjects.length, 157, "the recovered browser-authored topology is canonical");
assert.deepEqual(canonicalLayout.facilities.map((facility) => facility.id), [
  "editor-table-3",
  "editor-toilet-2",
  "home-cutting-table-01",
  "home-gas-stove-01",
  "home-juicer-01",
  "home-lemon-sack-01",
  "home-serving-table-01",
  "home-shower-01",
], "the latest canonical save removes the extra home table");
assert.deepEqual(canonicalLayout.furniture, [{
  id: "training-dummy-01",
  kind: "training-dummy",
  position: { x: 584, y: 480 },
}], "the training dummy position is part of the recovered canonical furniture layout");
assert.equal(canonicalLayout.facilities.some((facility) => (
  facility.footprint.x <= -10000 || facility.footprint.y <= -10000
)), false, "temporary facility staging coordinates never enter the canonical layout");
assert.throws(() => captureStartingLayout({
  ...captureScene(false),
  facilityRuntime: {
    getDefinitions: () => [{ id: "staged-facility", footprint: { x: -10256, y: -10000 } }],
  },
}), /temporary staging position/, "capture fails closed while a facility remains staged");
const corruptedDraftStorage = createStorage();
corruptedDraftStorage.setItem(STARTING_LAYOUT_STORAGE_KEY, JSON.stringify({
  ...canonicalLayout,
  facilities: [...canonicalLayout.facilities, {
    id: "staged-facility",
    footprint: { x: -10256, y: -10000 },
  }],
}));
const recoveredDraft = loadStartingLayout(corruptedDraftStorage, canonicalLayout);
assert.equal(recoveredDraft.facilities.some((facility) => facility.id === "staged-facility"), false);
assert.deepEqual(
  JSON.parse(corruptedDraftStorage.getItem(STARTING_LAYOUT_STORAGE_KEY)),
  recoveredDraft,
  "legacy browser drafts discard only temporary facility staging records",
);

const savedLayoutStorage = createStorage();
await saveStartingLayoutToProject(captureScene(false), {
  storage: savedLayoutStorage,
  fetchImpl: async () => ({ ok: true, text: async () => "" }),
});
assert.equal(savedLayoutStorage.getItem(STARTING_LAYOUT_STORAGE_KEY), null, "a successful project write clears its browser draft");

const failedLayoutStorage = createStorage();
await assert.rejects(() => saveStartingLayoutToProject(captureScene(false), {
  storage: failedLayoutStorage,
  fetchImpl: async () => ({ ok: false, status: 404, text: async () => "static host" }),
}), (error) => error.localSaved === true && /static host/.test(error.message));
assert.deepEqual(
  JSON.parse(failedLayoutStorage.getItem(STARTING_LAYOUT_STORAGE_KEY)),
  activeLayout,
  "a static-host project write failure must keep the newly authored room topology in browser storage",
);

const backupStorage = createStorage();
backupStorage.setItem(STARTING_LAYOUT_STORAGE_KEY, JSON.stringify(activeLayout));
saveColliderDebugOverrides(normalized, backupStorage);
const backup = createAuthoringBackup(backupStorage, new Date("2026-07-27T12:00:00.000Z"));
assert.equal(backup.version, AUTHORING_BACKUP_VERSION);
assert.equal(backup.savedAt, "2026-07-27T12:00:00.000Z");
assert.deepEqual(backup.startingLayout, activeLayout);
assert.deepEqual(backup.colliderOverrides, normalized);
const backupSource = createAuthoringBackupSource(backup);
assert(backupSource.endsWith("\n") && backupSource.includes('"colliderOverrides"'));
const restoredStorage = createStorage();
restoreAuthoringBackup(JSON.parse(backupSource), restoredStorage);
assert.deepEqual(JSON.parse(restoredStorage.getItem(STARTING_LAYOUT_STORAGE_KEY)), activeLayout);
assert.deepEqual(JSON.parse(restoredStorage.getItem(COLLIDER_DEBUG_STORAGE_KEY)), normalized);

console.log("authoring contracts passed: web drafts survive static hosting and backups roundtrip");
